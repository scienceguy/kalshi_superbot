# ─── Generation Functions ─────────────────────────────────────────────────────

def generate_service_units(output_dir: Path):
    """Generate systemd service unit files."""
    output_dir.mkdir(parents=True, exist_ok=True)

    for name, svc in SERVICES.items():
        user = svc.get("user", SERVICE_USER)
        group = svc.get("group", SERVICE_GROUP)
        after = ""
        if name in ["kalshi-trader", "polymarket-trader"]:
            after = "After=mempalace.service n8n.service\nWants=mempalace.service n8n.service"

        content = SERVICE_TEMPLATE.format(
            name=name,
            description=svc["description"],
            after=after,
            user=user,
            group=group,
            working_dir=WORKING_DIR,
            env_file=ENV_FILE,
            exec_start=svc["exec_start"],
            restart=svc["restart"],
            restart_sec=svc["restart_sec"],
            watchdog_sec=svc["watchdog_sec"],
        )

        (output_dir / f"{name}.service").write_text(content)
        print(f"Generated {output_dir}/{name}.service")


def generate_env_file(output_path: Path, secrets: Dict[str, str]):
    """Generate environment file from template."""
    content = ENV_TEMPLATE.format(
        kalshi_key_id=secrets.get("KALSHI_KEY_ID", ""),
        kalshi_key_file=secrets.get("KALSHI_KEY_FILE", "/home/ubuntu/.secrets/kalshi_private.pem"),
        poly_private_key=secrets.get("POLYMARKET_PRIVATE_KEY", ""),
        poly_rpc_url=secrets.get("POLYMARKET_RPC_URL", "https://polygon-rpc.com"),
        n8n_api_key=secrets.get("N8N_API_KEY", ""),
        supabase_url=secrets.get("SUPABASE_URL", ""),
        supabase_service_key=secrets.get("SUPABASE_SERVICE_KEY", ""),
        supabase_db_url=secrets.get("SUPABASE_DB_URL", ""),
        working_dir=WORKING_DIR,
    )
    output_path.write_text(content)
    print(f"Generated {output_path}")


def generate_all_configs(output_dir: Path = Path("/tmp/kalshi-systemd")):
    """Generate all systemd configuration files."""
    output_dir.mkdir(parents=True, exist_ok=True)

    # Service units
    units_dir = output_dir / "systemd"
    generate_service_units(units_dir)

    # Environment file (template)
    generate_env_file(output_dir / "kalshi-superbot.env", {})

    # Firewall script
    (output_dir / "kalshi-firewall.sh").write_text(FIREWALL_RULES)
    (output_dir / "kalshi-firewall.sh").chmod(0o755)

    # Chrony config
    (output_dir / "chrony.conf").write_text(CHRONY_CONF)

    # Logrotate config
    (output_dir / "logrotate.d").mkdir(parents=True, exist_ok=True)
    (output_dir / "logrotate.d" / "kalshi-superbot").write_text(LOGROTATE_CONF)

    # Litestream config template
    (output_dir / "litestream.yml").write_text(LITESTREAM_YML.format(
        s3_bucket="YOUR_BUCKET",
        s3_path="kalshi-superbot",
        s3_endpoint="https://s3.YOUR_REGION.amazonaws.com",
        s3_region="YOUR_REGION",
        access_key="YOUR_KEY",
        secret_key="YOUR_SECRET",
    ))

    # Setup script
    (output_dir / "setup_systemd.sh").write_text(SYSTEMD_SETUP_SCRIPT)
    (output_dir / "setup_systemd.sh").chmod(0o755)

    print(f"\nAll configs generated in {output_dir}")
    print("Run setup_systemd.sh as root to install")


if __name__ == "__main__":
    import sys

    if len(sys.argv) > 1 and sys.argv[1] == "generate":
        generate_all_configs()
    else:
        print("Usage: python -m systemd generate")
